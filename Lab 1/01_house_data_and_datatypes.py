# Program 1: Store and Display House Data with Data Types

# Store house information
house_size = 2000  # in sq. ft.
house_price = 60  # in Lakhs
city_name = "Mumbai"
is_available = True

# Display values
print ("House Size: ", house_size, "sq. ft.")
print ("House Price: ", house_price, "Lakhs")
print ("City Name: ", city_name)
print ("Availability Status: ", is_available)

# Display data types
print ("Data type of house_size: ", type(house_size))
print ("Data type of house_price: ", type(house_price))
print ("Data type of city_name: ", type(city_name))
print ("Data type of is_available: ", type(is_available))