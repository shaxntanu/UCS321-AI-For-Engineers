# Program 2: Calculate Operations on Two House Prices

# Store two house prices
price1 = 45  # in Lakhs
price2 = 30  # in Lakhs

# Perform calculations
total_cost = price1 + price2
difference = price1 - price2
multiplication = price1 * price2
division = price1 / price2

# Display results
print ("House 1 Price: ", price1, "Lakhs")
print ("House 2 Price: ", price2, "Lakhs")
print ("Total Cost: ", total_cost, "Lakhs")
print ("Difference: ", difference, "Lakhs")
print ("Multiplication: ", multiplication)
print ("Division: ", division)
